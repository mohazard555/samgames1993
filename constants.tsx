let gameCounter = 1;
const list: Game[] = [];

Object.entries(gameNamesByCategory).forEach(([category, names]) => {
  names.forEach((name) => {
    const currentId = gameCounter;
    list.push({
      id: currentId,
      name: name,
      description: `لعبة ${category} ممتعة`,
      category: category,
      color: colors[currentId % colors.length]
    });
    gameCounter++;
  });
});

export const GAMES: Game[] = list;
