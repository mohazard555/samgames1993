export interface QuizQuestion {
  id: number;
  question: string;
  image?: string;
  badge?: string;
  explanation?: string;
  options: string[];
  correctAnswer: string;
}

export interface ComparisonItem {
  label: string;
  emoji: string;
  value?: number | string;
  description?: string;
}

